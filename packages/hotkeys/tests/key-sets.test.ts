// Letters each layout types only with Shift. Letters match Shift exactly, so
// these are bound with Shift.
const SHIFT_LETTERS: Partial<Record<keyof typeof KEY_SETS, Array<string>>> = {
  SwissGerman: ['Ç', 'È', 'É', 'À'],
  Spanish: ['ª'],
  Portuguese: ['ª'],
  Italian: ['É', 'Ç'],
  Turkish: ['İ', 'É'],
  Bulgarian: ['Ы', 'Ѝ'],
}

describe.each(Object.entries(KEY_SETS))('%sKeys', (name, keys) => {
  it('lists keys the way normalizeKeyName writes them, with no A-Z or 0-9', () => {
    for (const key of keys) {
      expect(normalizeKeyName(key)).toBe(key)
      expect(key).not.toMatch(/^[A-Z0-9]$/)
    }
  })

  it('parses each key alone and with Mod, with no warnings', () => {
    for (const key of keys) {
      for (const hotkey of [key, `Mod+${key}`]) {
        const result = validateHotkey(hotkey)
        expect(result, hotkey).toMatchObject({ valid: true, warnings: [] })
        expect(
          formatForDisplay(hotkey as never, { platform: 'windows' }),
        ).toContain(key)
      }
    }
  })

  it('matches a key press that types the key', () => {
    const shiftLetters = SHIFT_LETTERS[name as keyof typeof KEY_SETS] ?? []
    for (const key of keys) {
      // Letters arrive lowercase. İ has no one-character lowercase.
      const typed =
        [...key.toLowerCase()].length === 1 ? key.toLowerCase() : key
      const shift = shiftLetters.includes(key)
      const event = new KeyboardEvent('keydown', {
        key: typed,
        code: 'IntlBackslash',
        shiftKey: shift,
      })
      const hotkey = shift ? `Shift+${key}` : key
      expect(
        matchesKeyboardEvent(event, hotkey as never, 'windows'),
        hotkey,
      ).toBe(true)
    }
  })
})
