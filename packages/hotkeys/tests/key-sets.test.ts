// tests/register-keys checks a program that registers keys. This one doesn't.
it('accepts the US QWERTY keys when no keys are registered', () => {
  expectTypeOf<LayoutKey>().toEqualTypeOf<UsKeys>()
  expectTypeOf<UsKeys>().toEqualTypeOf<PunctuationKey>()
  expectTypeOf<'Mod+/' | 'Mod+[' | '\\'>().toExtend<HotkeyChord>()
  expectTypeOf<Extract<'Mod+Ö' | 'ß' | 'Mod+É', HotkeyChord>>().toBeNever()
})

